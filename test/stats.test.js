'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { parseStats, itemsFromText, duration, ratio } = require('../src/stats')
const items = itemsFromText(fs.readFileSync(path.join(__dirname, 'fixtures/hoplite-stats.txt'), 'utf8'))

test('real lore becomes nine useful categories with accurate overall ratios', () => {
  const data = parseStats(items)
  assert.equal(data.modes.length, 2)
  assert.equal(data.classes.length, 6)
  assert.equal(data.overall.gamesPlayed, 4)
  assert.equal(data.overall.losses, 3)
  assert.equal(data.overall.deaths, 5)
  assert.equal(data.overall.killDeathRatio, 3.2)
  assert.equal(data.overall.winLossRatio, 1 / 3)
  assert.equal(data.overall.winRate, 25)
  assert.equal(data.overall.playtimeSeconds, 5106)
  assert.equal(data.overall.averageSurvivalSeconds, 1277)
  assert.equal(data.overall.voicechatRank, 0)
  assert.equal(data.overall.legendaryKills, 6)
  assert.equal(data.modes[0].losses, 2)
  assert.equal(data.modes[0].winLossRatio, 0.5)
  assert.equal(data.modes[0].deaths, 2)
  assert.equal(data.modes[0].killDeathRatio, 8)
  assert.equal(data.modes[1].deaths, 3)
  assert.equal(data.modes[1].killDeathRatio, 0)
  assert.equal(data.modes[1].winLossRatio, 0)
  assert.equal(data.classes[1].winLossRatio, 1)
  assert.equal(data.classes[1].killDeathRatio, 16)
  assert.equal(data.classes[2].killDeathRatio, 0)
})

test('overall K/D requires all classes and uses kit totals when overall kills disagree', () => {
  const incomplete = parseStats(items.filter(item => item.name !== 'Miner Stats'))
  assert.equal(incomplete.overall.killDeathRatio, null)
  const changed = items.map(item => item.name === 'Warrior Stats' ? { ...item, tooltip: item.tooltip.replace('Kills: 16', 'Kills: 15') } : item)
  assert.equal(parseStats(changed).overall.killDeathRatio, 3)
})

test('missing values remain unavailable, zero and infinity remain distinct', () => {
  assert.equal(ratio(0, 0), 0)
  assert.equal(ratio(5, 0), '∞')
  assert.equal(ratio(5, null), null)
  assert.equal(duration('00:01:11:50'), 4310)
  assert.equal(duration('01:00:00:00'), 86400)
  assert.equal(duration('00:00:60:00'), null)
  assert.equal(duration('unknown'), null)
  const data = parseStats([{ id: 1, name: 'Overall Stats', tooltip: 'Games Played: 0\nWins: 0' }])
  assert.equal(data.overall.winRate, 0)
  assert.equal(data.overall.killDeathRatio, null)
})

test('Civ deaths use overall minus Solo even when game totals differ, and never become negative', () => {
  const mismatch = items.map(item => item.name === 'Civilization Stats' ? { ...item, tooltip: item.tooltip.replace('Games Played: 1', 'Games Played: 2') } : item)
  assert.equal(parseStats(mismatch).modes[1].deaths, 3)
  assert.equal(parseStats(mismatch).modes[1].killDeathRatio, 0)
  const noClasses = parseStats(items.filter(item => !/^(Miner|Warrior|Trapper|Archer|Looter|Fisherman) Stats$/.test(item.name)))
  assert.equal(noClasses.modes[0].killDeathRatio, 8)
  assert.equal(noClasses.modes[1].killDeathRatio, null)
  const impossible = items.map(item => /^(Miner|Warrior) Stats$/.test(item.name) ? { ...item, tooltip: item.tooltip.replace(/Deaths: \d+/, 'Deaths: 0') } : item)
  assert.equal(parseStats(impossible).modes[1].deaths, undefined)
})

test('playtime omits seconds only when it includes days', () => {
  const { time } = require('../src/stats')
  assert.equal(time(86400 + 3600 + 120 + 59), '1d 1h 2m')
  assert.equal(time(86401), '1d')
  assert.equal(time(86399), '23h 59m 59s')
  assert.equal(time(null), '—')
})

test('zero deaths count as one for K/D without changing deaths or W/L', () => {
  const data = parseStats([{ id: 0, name: 'Miner Stats', tooltip: 'Kills: 5\nDeaths: 0\nWins: 3\nLosses: 0' }])
  assert.equal(data.classes[0].killDeathRatio, 5)
  assert.equal(data.classes[0].deaths, 0)
  assert.equal(data.classes[0].winLossRatio, 3)
  const zero = parseStats([{ id: 0, name: 'Miner Stats', tooltip: 'Kills: 0\nDeaths: 0' }])
  assert.equal(zero.classes[0].killDeathRatio, 0)
})

test('Duels separates summary entries from named kits and preserves streaks', () => {
  const { parseDuelsStats } = require('../src/stats')
  const names = ['Kit', 'Competitive', 'Custom Kit', 'Private', 'Sword', 'Battle Royale']
  const data = parseDuelsStats(names.map((name, id) => ({ id, name: name + ' Stats', tooltip: 'Kills: 5\nDeaths: 0\nCurrent Winstreak: 2\nBest Winstreak: 4' })))
  assert.deepEqual(data.overall.map(item => item.name), ['Overall', 'Competitive', 'Custom', 'Private'])
  assert.deepEqual(data.kits.map(item => item.name), ['Sword', 'Battle Royale'])
  assert.equal(data.overall[0].winStreak, 2)
  assert.equal(data.overall[0].bestWinStreak, 4)
  assert.equal(data.kits[0].killDeathRatio, 5)
})
